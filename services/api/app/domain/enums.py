    CREATED = "CREATED"
    AUTHENTICATED = "AUTHENTICATED"
    ACTIVE = "ACTIVE"
    PENDING = "PENDING"
    HALTED = "HALTED"
    PAUSED = "PAUSED"
    CANCELLED = "CANCELLED"
    COMPLETED = "COMPLETED"


