    OPEN = "OPEN"
    RECOVERED = "RECOVERED"
    PARTIALLY_RECOVERED = "PARTIALLY_RECOVERED"
    ESCALATED = "ESCALATED"
    DISPUTED = "DISPUTED"
    STOPPED = "STOPPED"
    EXPIRED = "EXPIRED"


